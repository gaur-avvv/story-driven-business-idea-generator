import React, { useState } from 'react';
import type { BusinessIdea } from '../types';
import type { Mode } from '../App';
import { AudioPlayer } from './AudioPlayer';
import { Icon } from './Icon';
import { t, Language } from '../utils/i18n';
import { downloadTextFile, downloadAudio } from '../utils/download';
import { NotionModal } from './NotionModal';

const SwotRadarChart = React.lazy(() => import('./SwotRadarChart'));

interface ResultCardProps {
  idea: BusinessIdea;
  mode: Mode;
  audioData: string | null;
  language: Language;
  onRegenerate: (refinementInput: string) => void;
  isRefining: boolean;
  onFeedback?: (rating: 'up' | 'down') => void;
  currentFeedback?: 'up' | 'down' | null;
  onShare?: () => void;
  onGeneratePitchDeck?: () => void;
  isGeneratingPitchDeck?: boolean;
}

const ResultSection: React.FC<{ title: string; icon: string; children: React.ReactNode }> = ({ title, icon, children }) => (
    <div className="border-t border-border-subtle pt-6">
        <h3 className="text-lg font-semibold text-brand-primary flex items-center mb-3">
            <Icon name={icon} className="w-5 h-5 mr-2.5" />
            {title}
        </h3>
        <div className="text-text-secondary max-w-none">
            {children}
        </div>
    </div>
);

const ActionButton: React.FC<{ onClick: () => void; icon: string; disabled?: boolean; children: React.ReactNode }> = ({ onClick, icon, disabled, children }) => (
    <button
        onClick={onClick}
        disabled={disabled}
        className="btn-ghost"
    >
        <Icon name={icon} className="w-4 h-4" />
        <span>{children}</span>
    </button>
);

export const ResultCard: React.FC<ResultCardProps> = ({
  idea,
  mode,
  audioData,
  language,
  onRegenerate,
  isRefining,
  onFeedback,
  currentFeedback,
  onShare,
  onGeneratePitchDeck,
  isGeneratingPitchDeck
}) => {
    const [refinementInput, setRefinementInput] = useState('');
    const [isNotionModalOpen, setIsNotionModalOpen] = useState(false);

    const content = {
        new: {
            insightTitle: t(language, 'insightTitleNew'),
            insightIcon: "market",
            storyTitle: t(language, 'storyTitleNew'),
        },
        improve: {
            insightTitle: t(language, 'insightTitleImprove'),
            insightIcon: "chart-bar",
            storyTitle: t(language, 'storyTitleImprove'),
        }
    };

    const { insightTitle, insightIcon, storyTitle } = content[mode];

    const handleDownloadIdea = () => {
        const sections = [
            `# ${idea.idea}`,
            `## ${insightTitle}`,
            idea.marketInsight,
            `## ${t(language, 'corePrincipleTitle')}`,
            idea.corePrinciple,
            `## ${storyTitle}`,
            idea.story || '',
        ];
        if (idea.sources && idea.sources.length > 0) {
            sections.push(`## ${t(language, 'sourcesTitle')}`);
            const sourceLinks = idea.sources.map(s => `- [${s.title}](${s.uri})`).join('\n');
            sections.push(sourceLinks);
        }
        const markdownContent = sections.join('\n\n');
        downloadTextFile(markdownContent, `${(idea.idea || 'idea').slice(0, 20)}.md`, 'text/markdown');
    };

    const handleDownloadAudio = () => {
        if (audioData) {
            downloadAudio(audioData, `${(idea.idea || 'idea').slice(0, 20)}`);
        }
    };

    const handleRefineSubmit = (e: React.FormEvent) => {
        e.preventDefault();
        if (refinementInput.trim()) {
            onRegenerate(refinementInput);
        }
    };

    const handleShare = () => {
      const summary = `${idea.idea}\n\nMarket Insight: ${idea.marketInsight}\n\nCore Principle: ${idea.corePrinciple}\n\nGenerated by Story-Driven Business Idea Generator`;
      navigator.clipboard.writeText(summary);
      onShare?.();
    };

    const handleWhatsAppShare = () => {
      const text = encodeURIComponent(`Check out this business idea: *${idea.idea}*\n\nInsight: ${idea.marketInsight}\n\nPrinciple: ${idea.corePrinciple}`);
      window.open(`https://wa.me/?text=${text}`, '_blank');
    };

    const handleTelegramShare = () => {
      const text = encodeURIComponent(`Business Idea: ${idea.idea}\n\nInsight: ${idea.marketInsight}\n\nPrinciple: ${idea.corePrinciple}`);
      window.open(`https://t.me/share/url?url=${window.location.href}&text=${text}`, '_blank');
    };

  return (
    <div className="card sheen rounded-2xl p-6 md:p-10 space-y-8 animate-reveal relative overflow-hidden group">
      {/* Decorative gradient wash */}
      <div className="absolute -top-28 -right-28 w-72 h-72 bg-brand-primary/10 rounded-full blur-3xl group-hover:bg-brand-primary/15 transition-colors duration-1000 pointer-events-none"></div>
      <div className="absolute -bottom-32 -left-24 w-72 h-72 bg-brand-accent/8 rounded-full blur-3xl pointer-events-none"></div>

      <div className="text-center relative z-10">
        <span className="eyebrow">{mode === 'new' ? 'New Concept' : 'Improvement Plan'}</span>
        <h2 className="mt-3 text-2xl md:text-3xl lg:text-4xl font-display font-bold text-text-primary leading-tight max-w-[20ch] mx-auto">
          {idea.idea}
        </h2>
        {/* Feedback */}
        <div className="flex justify-center items-center mt-6 gap-4">
          <button
            onClick={() => onFeedback?.('up')}
            className={`flex items-center gap-2 px-4 py-2 rounded-xl transition-all border ${currentFeedback === 'up' ? 'bg-success/12 border-success/50 text-success' : 'bg-background-secondary border-border-subtle text-text-muted hover:border-success/40 hover:text-success'}`}
          >
            <Icon name="thumbUp" className="w-4 h-4" />
            <span className="text-xs font-bold uppercase tracking-widest">Brilliant</span>
          </button>
          <button
            onClick={() => onFeedback?.('down')}
            className={`flex items-center gap-2 px-4 py-2 rounded-xl transition-all border ${currentFeedback === 'down' ? 'bg-error/12 border-error/50 text-error' : 'bg-background-secondary border-border-subtle text-text-muted hover:border-error/40 hover:text-error'}`}
          >
            <Icon name="thumbDown" className="w-4 h-4" />
            <span className="text-xs font-bold uppercase tracking-widest">Off Mark</span>
          </button>
        </div>
      </div>

      {/* Action bar */}
      <div className="flex flex-wrap justify-center items-center gap-3 py-5 border-y border-border-subtle relative z-10">
        <ActionButton onClick={handleDownloadIdea} icon="download">
            {t(language, 'downloadIdea')}
        </ActionButton>
        <ActionButton onClick={handleDownloadAudio} icon="download" disabled={!audioData}>
            {t(language, 'downloadAudio')}
        </ActionButton>
        <div className="flex items-center gap-2">
            <button
                onClick={handleShare}
                className="flex items-center gap-2 px-4 py-2.5 bg-brand-primary/10 text-brand-primary rounded-xl border border-brand-primary/20 hover:bg-brand-primary hover:text-white transition-all font-bold text-sm"
                title="Copy to Clipboard"
            >
                <Icon name="share" className="w-4 h-4" />
                {t(language, 'shareIdea')}
            </button>
            <button
                onClick={handleWhatsAppShare}
                className="p-2.5 bg-success/12 text-success rounded-xl border border-success/25 hover:bg-success hover:text-white transition-all"
                title="Share on WhatsApp"
            >
                <Icon name="message" className="w-5 h-5" />
            </button>
            <button
                onClick={handleTelegramShare}
                className="p-2.5 bg-info/12 text-info rounded-xl border border-info/25 hover:bg-info hover:text-white transition-all"
                title="Share on Telegram"
            >
                <Icon name="send" className="w-5 h-5" />
            </button>
        </div>
        <button
          onClick={onGeneratePitchDeck}
          disabled={isGeneratingPitchDeck || !!idea.pitchDeck}
          className="flex items-center gap-2 px-5 py-2.5 bg-brand-accent/12 text-brand-accent rounded-xl border border-brand-accent/25 hover:bg-brand-accent hover:text-white transition-all font-bold text-sm disabled:opacity-50 disabled:cursor-not-allowed"
        >
          <Icon name={isGeneratingPitchDeck ? 'loading' : 'sparkles'} className={`w-4 h-4 ${isGeneratingPitchDeck ? 'animate-spin' : ''}`} />
          {isGeneratingPitchDeck ? 'Drafting...' : idea.pitchDeck ? 'Pitch Deck Ready' : 'Generate Pitch Deck'}
        </button>
        <button
          onClick={() => setIsNotionModalOpen(true)}
          className="btn-ghost"
        >
          <Icon name="bookmark" className="w-4 h-4 text-brand-primary" />
          Save to Notion
        </button>
      </div>

      <ResultSection title={insightTitle} icon={insightIcon}>
          <p>{idea.marketInsight}</p>
      </ResultSection>

      {idea.marketScarcity && (
        <ResultSection title="Market Scarcity" icon="lock">
            <p className="text-success font-medium italic">Why this is rare: {idea.marketScarcity}</p>
        </ResultSection>
      )}

      <ResultSection title={t(language, 'corePrincipleTitle')} icon="book">
          <p>{idea.corePrinciple}</p>
      </ResultSection>

      <ResultSection title={storyTitle} icon="story">
        <AudioPlayer audioData={audioData} storyText={idea.story} />
        <div className="mt-4 space-y-3">
          {(idea.story || '').split('\n').filter(p => p.trim() !== '').map((paragraph, index) => (
            <p key={index}>{paragraph}</p>
          ))}
        </div>
      </ResultSection>

      {idea.pitchDeck && (
        <ResultSection title="Draft Pitch Deck" icon="presentation">
            <div className="bg-background-secondary p-6 rounded-xl border border-success/30">
                <div className="space-y-1 text-text-secondary" dangerouslySetInnerHTML={{ __html: idea.pitchDeck.replace(/\n/g, '<br/>') }} />
            </div>
        </ResultSection>
      )}

      {idea.nextSteps && idea.nextSteps.length > 0 && (
        <ResultSection title="Execution Roadmap" icon="idea">
            <div className="grid grid-cols-1 gap-3">
                {idea.nextSteps.map((step, i) => (
                    <div key={i} className="flex items-start gap-4 p-4 bg-brand-primary/5 rounded-xl border border-brand-primary/10 hover:bg-brand-primary/10 transition-all">
                        <div className="w-8 h-8 rounded-full bg-gradient-brand text-white flex items-center justify-center font-black text-xs shrink-0 shadow-md">
                            {i + 1}
                        </div>
                        <p className="text-text-primary font-medium pt-1">{step}</p>
                    </div>
                ))}
            </div>
        </ResultSection>
      )}

      {idea.swot && (
        <ResultSection title="Strategic SWOT Matrix" icon="chart-bar">
            <div className="flex justify-end mb-2">
                <button
                  onClick={() => {
                    const swotText = `### SWOT Analysis: ${idea.idea}\n\n` +
                      `**Strengths:**\n${idea.swot?.strengths.map(s => `- ${s}`).join('\n')}\n\n` +
                      `**Weaknesses:**\n${idea.swot?.weaknesses.map(s => `- ${s}`).join('\n')}\n\n` +
                      `**Opportunities:**\n${idea.swot?.opportunities.map(s => `- ${s}`).join('\n')}\n\n` +
                      `**Threats:**\n${idea.swot?.threats.map(s => `- ${s}`).join('\n')}`;
                    navigator.clipboard.writeText(swotText);
                    onShare?.();
                  }}
                  className="text-[10px] font-bold uppercase tracking-widest text-brand-primary hover:text-brand-accent flex items-center gap-1 bg-brand-primary/5 px-2 py-1 rounded border border-brand-primary/20 transition-all"
                >
                    <Icon name="share" className="w-3 h-3" />
                    Copy SWOT Markdown
                </button>
            </div>
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4 mt-2">
                <div className="bg-quadrant-strength-light border border-quadrant-strength/25 p-4 rounded-xl">
                    <h4 className="text-quadrant-strength font-bold text-xs uppercase tracking-widest mb-2">Strengths</h4>
                    <ul className="space-y-1">
                        {idea.swot.strengths.map((s, i) => <li key={i} className="text-sm text-text-secondary flex gap-2"><span className="text-quadrant-strength">•</span>{s}</li>)}
                    </ul>
                </div>
                <div className="bg-quadrant-weakness-light border border-quadrant-weakness/25 p-4 rounded-xl">
                    <h4 className="text-quadrant-weakness font-bold text-xs uppercase tracking-widest mb-2">Weaknesses</h4>
                    <ul className="space-y-1">
                        {idea.swot.weaknesses.map((s, i) => <li key={i} className="text-sm text-text-secondary flex gap-2"><span className="text-quadrant-weakness">•</span>{s}</li>)}
                    </ul>
                </div>
                <div className="bg-quadrant-opportunity-light border border-quadrant-opportunity/25 p-4 rounded-xl">
                    <h4 className="text-quadrant-opportunity font-bold text-xs uppercase tracking-widest mb-2">Opportunities</h4>
                    <ul className="space-y-1">
                        {idea.swot.opportunities.map((s, i) => <li key={i} className="text-sm text-text-secondary flex gap-2"><span className="text-quadrant-opportunity">•</span>{s}</li>)}
                    </ul>
                </div>
                <div className="bg-quadrant-threat-light border border-quadrant-threat/25 p-4 rounded-xl">
                    <h4 className="text-quadrant-threat font-bold text-xs uppercase tracking-widest mb-2">Threats</h4>
                    <ul className="space-y-1">
                        {idea.swot.threats.map((s, i) => <li key={i} className="text-sm text-text-secondary flex gap-2"><span className="text-quadrant-threat">•</span>{s}</li>)}
                    </ul>
                </div>
            </div>
            <React.Suspense
              fallback={
                <div className="h-80 w-full flex items-center justify-center">
                  <div className="flex items-center gap-1.5" aria-hidden="true">
                    <span className="w-2 h-2 bg-brand-primary rounded-full animate-bounce" style={{ animationDelay: '0ms' }}></span>
                    <span className="w-2 h-2 bg-brand-primary rounded-full animate-bounce" style={{ animationDelay: '120ms' }}></span>
                    <span className="w-2 h-2 bg-brand-primary rounded-full animate-bounce" style={{ animationDelay: '240ms' }}></span>
                  </div>
                </div>
              }
            >
              <SwotRadarChart idea={idea} />
            </React.Suspense>
        </ResultSection>
      )}

      {idea.sources && idea.sources.length > 0 && (
        <ResultSection title={t(language, 'sourcesTitle')} icon="search">
            <ul className="list-disc pl-5 space-y-2 text-sm">
                {idea.sources.map((source, index) => (
                    <li key={index}>
                        <a href={source.uri} target="_blank" rel="noopener noreferrer" className="text-brand-primary hover:text-brand-accent hover:underline underline-offset-2 transition-colors">
                            {source.title}
                        </a>
                    </li>
                ))}
            </ul>
        </ResultSection>
      )}

      {/* Refinement */}
      <div className="border-t border-border-subtle pt-6">
        <h3 className="text-lg font-semibold text-brand-primary flex items-center mb-3">
            <Icon name="sparkles" className="w-5 h-5 mr-3" />
            {t(language, 'refineTitle')}
        </h3>
        <form onSubmit={handleRefineSubmit} className="space-y-3">
             <textarea
                value={refinementInput}
                onChange={(e) => setRefinementInput(e.target.value)}
                placeholder={t(language, 'refinePlaceholder')}
                className="input-field max-h-40 resize-y"
                rows={2}
                disabled={isRefining}
            />
            <button
                type="submit"
                disabled={isRefining || !refinementInput.trim()}
                className="btn-primary w-full"
            >
                <Icon name="sparkles" className="w-5 h-5" />
                {isRefining ? t(language, 'refining') : t(language, 'refineButton')}
            </button>
        </form>
      </div>

      <NotionModal
        isOpen={isNotionModalOpen}
        onClose={() => setIsNotionModalOpen(false)}
        idea={idea}
        language={language}
      />
    </div>
  );
};
